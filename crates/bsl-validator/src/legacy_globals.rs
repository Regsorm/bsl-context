//! Устаревшие, но живые глобальные методы платформы (issue #40).
//!
//! Платформенный контекст строится ТОЛЬКО из справки (`shcntx_ru.hbk`), а 1С
//! часть глобальных методов из справки убрала, оставив их в платформе ради
//! совместимости. Такой вызов попадает в ветку «точного имени нет», и если имя
//! ни на что не похоже, `check_global_calls` выдаёт `undeclared_method` с
//! `confidence: high` — то есть рабочий код объявляется нерабочим.
//!
//! Список **точечный** и намеренно НЕ обобщается правилом «похоже на
//! платформенное — молчим»: под такое правило попадает и настоящая опечатка
//! (`Сообщитть`), ради которой проверка и написана. Родственный приём для
//! значений перечислений — [`crate::enum_values`].
//!
//! Пополнять список можно только по проверенному факту: имя исполняется
//! платформой целевой версии, а справка его не описывает. Основания записываются
//! в комментарии к записи.
//!
//! Основной внешний источник — официальный список устаревших методов: changelog
//! 8.3.10 («Следующие методы глобального контекста объявляются устаревшими…»,
//! dl03.1c.ru). Тот же список продублирован диагностикой BSL Language Server
//! `DeprecatedMethods8310` — по ней удобно сверять английские имена.

use crate::homoglyphs::same_after_fold;

/// Имена, которые платформа исполняет, хотя справка целевой версии их уже не
/// описывает (в 8.3.27 — все, кроме последнего: `ТекущийВариантИнтерфейса…`
/// справка ещё описывает, и запись там работает только на других версиях).
///
/// Регистр и алфавитные двойники не важны: сравнение идёт через
/// [`same_after_fold`], как и у остальных имён платформенного контекста.
const LEGACY_GLOBAL_METHODS: &[&str] = &[
    // Семейство заголовка приложения. Автор issue проверил живым прогоном на
    // 8.3.17.1549 и 8.3.19.1529: заголовок доезжает до окна ОС, ошибки нет.
    // Документация 1С: `УстановитьЗаголовокПриложения` доступна на всех видах
    // клиента и «начиная с версии 8.3 считается устаревшей и оставлена только
    // для совместимости»; пара с «Клиентского» появилась в 8.3.3 и устарела в
    // 8.3.10 (диагностика BSL Language Server `DeprecatedMethods8310`). Замена —
    // методы объекта `КлиентскоеПриложение`: `УстановитьЗаголовок`,
    // `ПолучитьЗаголовок`, `УстановитьКраткийЗаголовок`, `ПолучитьКраткийЗаголовок`.
    // В справке 8.3.27 этих имён нет: `search`/`info`/индекс платформы их не
    // находят (проверено на живом сервере при разборе issue #40).
    "УстановитьЗаголовокПриложения",
    "ПолучитьЗаголовокПриложения",
    "УстановитьКраткийЗаголовокПриложения",
    "ПолучитьКраткийЗаголовокПриложения",
    "УстановитьЗаголовокКлиентскогоПриложения",
    "ПолучитьЗаголовокКлиентскогоПриложения",
    // Варианты шрифта и интерфейса клиентского приложения — из того же списка
    // 8.3.10. `ТекущийВариантОсновногоШрифтаКлиентскогоПриложения` проверен на
    // нашем стенде: имя получало `undeclared_method` с `confidence: high` на
    // пустом месте. Соседнее `ТекущийВариантИнтерфейсаКлиентскогоПриложения`
    // справка 8.3.27 ещё описывает (находки нет), но в списке оно стоит на случай
    // версий платформы, где страницы уже нет.
    "ТекущийВариантОсновногоШрифтаКлиентскогоПриложения",
    "ТекущийВариантИнтерфейсаКлиентскогоПриложения",
];

/// Имя глобального метода известно платформе, хотя справка его и не описывает?
///
/// `true` — вызов не считается ни опечаткой, ни забытым объявлением: сигнатуры
/// у нас нет, поэтому проверка арности для таких имён тоже не выполняется.
pub fn is_legacy_global_method(name: &str) -> bool {
    LEGACY_GLOBAL_METHODS
        .iter()
        .any(|known| same_after_fold(known, name))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn caption_family_is_recognized() {
        for name in [
            "УстановитьЗаголовокПриложения",
            "ПолучитьЗаголовокПриложения",
            "УстановитьКраткийЗаголовокПриложения",
            "ПолучитьКраткийЗаголовокПриложения",
            "УстановитьЗаголовокКлиентскогоПриложения",
            "ПолучитьЗаголовокКлиентскогоПриложения",
            "ТекущийВариантОсновногоШрифтаКлиентскогоПриложения",
            "ТекущийВариантИнтерфейсаКлиентскогоПриложения",
        ] {
            assert!(is_legacy_global_method(name), "{name}");
        }
    }

    #[test]
    fn case_is_ignored() {
        assert!(is_legacy_global_method("установитьзаголовокприложения"));
    }

    #[test]
    fn neighbours_are_not_recognized() {
        // Соседние имена списком не покрываются: опечатка в самом устаревшем
        // имени и «похожее» имя остаются находками.
        for name in [
            "УстановитьЗаголовокПриложения123",
            "УстановитьЗаголовокПриложени",
            "Сообщитть",
            "УстановитьРежимОсновногоОкна",
        ] {
            assert!(!is_legacy_global_method(name), "{name}");
        }
    }
}
