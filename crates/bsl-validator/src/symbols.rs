//! Внешний источник имён: методы, объявленные в ДРУГИХ модулях конфигурации.
//!
//! Валидатор видит только присланный текст. Отсюда ложные `UndeclaredMethod`
//! на процедурах глобальных общих модулей (зовутся без префикса откуда угодно)
//! и на модулях обычных форм внешних обработок (видят экспортные методы модуля
//! объекта-владельца). Источник закрывает ровно эти два случая и, кроме того,
//! позволяет понизить уверенность находки, если имя вообще где-то объявлено.

use std::collections::HashSet;

/// Поле объекта конфигурации: реквизит, измерение или ресурс.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ObjectField {
    pub name: String,
    /// Значение `<Indexing>` из выгрузки (`Index`, `IndexWithAdditionalOrder`).
    /// `None` — поле не индексировано: в выгрузке `DontIndex` не записывается.
    pub indexing: Option<String>,
}

impl ObjectField {
    /// Поле с индексом? `DontIndex`/пусто индексом не является: инвариант
    /// держится фильтрацией в источниках, но публичный метод обязан
    /// различать сам (иначе чужой producer молча выключит правило).
    pub fn is_indexed(&self) -> bool {
        self.indexing
            .as_deref()
            .is_some_and(|v| !v.is_empty() && !v.eq_ignore_ascii_case("DontIndex"))
    }
}

/// Состав объекта конфигурации — ровно то, что нужно правилам оптимальности
/// запросов, без полей «на будущее».
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ObjectSchema {
    pub attributes: Vec<ObjectField>,
    pub dimensions: Vec<ObjectField>,
    pub resources: Vec<ObjectField>,
    /// Табличные части объекта. В модуле объекта их имена видны без префикса
    /// (`Товары.Очистить()`), но в справке платформы их нет — состав знает
    /// только источник имён (issue #42).
    pub tabular_sections: Vec<ObjectField>,
    /// Вид регистра накопления: `Balance` (остатки) или `Turnovers` (обороты).
    /// Только для регистров накопления; у прочих объектов `None`.
    pub register_type: Option<String>,
    /// Значения перечисления — только у объектов коллекции `Enums`
    /// (`enum_values` из `attributes_json`). Пустой список означает «источник
    /// значений не отдал»: правило по `Перечисления.<Имя>.<Значение>` обязано в
    /// этом случае молчать целиком, иначе выдуманное значение неотличимо от
    /// законного (issue #41).
    pub enum_values: Vec<String>,
}

/// Счётчики состава источника имён — для `symbol_sources_status` (issue #46).
///
/// Ответ «объект не существует» убедителен ровно настолько, насколько полон
/// источник. Пустой или почти пустой индекс отвечает так же уверенно, как
/// полный, и вызывающий не может отличить одно от другого: этих чисел в статусе
/// не было.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct SourceStats {
    /// Сколько объектов конфигурации знает источник.
    pub objects: usize,
    /// Сколько имён (объектов вместе с методами и переменными) в индексе.
    pub names: usize,
}

impl ObjectSchema {
    /// Регистр остатков — у него есть виртуальные таблицы `Остатки`
    /// и `ОстаткиИОбороты`, ради которых физическую таблицу читать не нужно.
    pub fn is_balance_register(&self) -> bool {
        self.register_type
            .as_deref()
            .is_some_and(|v| v.trim().eq_ignore_ascii_case("Balance"))
    }

    /// Найти поле среди реквизитов, измерений и ресурсов.
    /// Имя сворачивается в Rust: SQLite-подобный `lower()` кириллицу не берёт.
    /// Регистр аргумента значения не имеет.
    pub fn field(&self, name_lower: &str) -> Option<&ObjectField> {
        let key = name_lower.to_lowercase();
        self.attributes
            .iter()
            .chain(self.dimensions.iter())
            .chain(self.resources.iter())
            .find(|f| f.name.to_lowercase() == key)
    }

    /// Имя видно в модуле ВЛАДЕЛЬЦА без префикса: реквизит объекта, измерение,
    /// ресурс или табличная часть? В модуле объекта такие имена законны
    /// (`Товары.Очистить()`), хотя в справке платформы их нет вовсе — правило
    /// голов обязано их пропускать (issue #42, п. 2).
    ///
    /// От [`Self::field`] отличается составом: табличные части входят, а логика
    /// «поля запроса» на них не распространяется.
    pub fn implicit_name(&self, name_lower: &str) -> bool {
        let key = name_lower.to_lowercase();
        self.attributes
            .iter()
            .chain(self.dimensions.iter())
            .chain(self.resources.iter())
            .chain(self.tabular_sections.iter())
            .any(|f| f.name.to_lowercase() == key)
    }

    /// Значение перечисления с таким именем есть в составе? `enum_values` пуст —
    /// состав не отдан, и вопрос некорректен: вызывающий обязан проверить
    /// [`Self::enum_values`] сам (issue #41).
    pub fn has_enum_value(&self, name_lower: &str) -> bool {
        let key = name_lower.to_lowercase();
        self.enum_values
            .iter()
            .any(|value| value.to_lowercase() == key)
    }
}

pub trait SymbolSource: Send + Sync {
    /// Экспортный метод ГЛОБАЛЬНОГО общего модуля — такой зовут без префикса
    /// откуда угодно, находкой он быть не может.
    /// Умеют все три источника (`lite`, `code_index_db`, `code_index_mcp`):
    /// признак «Глобальный» читается из XML общего модуля. Дефолт `false` —
    /// для источника, который такого признака не знает.
    fn is_global_export(&self, _name_lower: &str) -> bool {
        false
    }

    /// Метод с таким именем объявлен ГДЕ-НИБУДЬ в конфигурации.
    /// Не основание молчать: вызов может быть недоступен отсюда по правилам
    /// видимости. Основание понизить уверенность находки.
    fn method_exists(&self, name_lower: &str) -> bool;

    /// Экспортные методы модуля объекта-владельца — для модуля обычной формы
    /// внешней обработки. `None` — источник не знает про такой модуль.
    fn owner_exports(&self, _module_path: &str) -> Option<HashSet<String>> {
        None
    }

    /// Источник УМЕЕТ вывести модуль-владельца для такого пути (раскладка
    /// распознана) — независимо от того, есть ли владелец в базе.
    ///
    /// Нужен, чтобы различить два случая, которые `owner_exports` отдаёт
    /// одинаково — `None`:
    ///
    /// * «владельца в источнике нет» — молчание проверок глобальных вызовов
    ///   обосновано: вызов без префикса может быть методом владельца;
    /// * «раскладка пути не поддерживается, спросить не умеем» — молчание
    ///   НЕобоснованно: под него попадали все модули форм конфигурации
    ///   (`<Вид>/<Имя>/Forms/<Форма>/Ext/Form/Module.bsl`), и настоящие опечатки
    ///   в них перестали находиться.
    ///
    /// Дефолт `false`: источник не заявляет умения, и валидатор проверяет
    /// глобальные вызовы как раньше.
    fn owner_resolvable(&self, _module_path: &str) -> bool {
        false
    }

    /// Объект конфигурации с таким именем существует в указанной коллекции.
    /// `collection` — во множественном числе, как каталог выгрузки:
    /// "CommonModules", "Catalogs", "Documents", ...
    /// `name_lower` — имя в нижнем регистре.
    /// `None` — источник не умеет ответить (тогда валидатор обязан молчать).
    fn object_exists(&self, _collection: &str, _name_lower: &str) -> Option<bool> {
        None
    }

    /// Все имена объектов коллекции (в ИСХОДНОМ регистре) — для подсказки
    /// «возможно, вы имели в виду». `None` — подсказки не будет.
    fn collection_names(&self, _collection: &str) -> Option<HashSet<String>> {
        None
    }

    /// Состав объекта: реквизиты, измерения, ресурсы, признак индексирования,
    /// вид регистра. Нужен правилам оптимальности запросов.
    ///
    /// `None` — источник не умеет ответить, и правило обязано промолчать
    /// ЦЕЛИКОМ. Разница с `Some(schema)`, где нужного поля не нашлось,
    /// принципиальна: во втором случае мы знаем состав и вправе делать выводы,
    /// в первом — не знаем ничего.
    fn object_schema(&self, _collection: &str, _name_lower: &str) -> Option<ObjectSchema> {
        None
    }

    /// Экспортные переменные модулей приложения (`Перем ПараметрыПриложения
    /// Экспорт;` в `ManagedApplicationModule` и подобных), в нижнем регистре.
    ///
    /// Такое имя видно БЕЗ префикса из любого клиентского модуля, поэтому для
    /// проверки это глобальное имя наравне с экспортным методом глобального
    /// общего модуля. Общий модуль переменных иметь не может — других
    /// источников таких имён нет.
    ///
    /// `None` — источник не умеет ответить. Проверка «неизвестный общий модуль»
    /// обязана в этом случае молчать ЦЕЛИКОМ: не зная этих имён, она принимает
    /// `ПараметрыПриложения.Вставить(...)` за обращение к несуществующему
    /// модулю (замер на УТ: 123 ложные находки на одном лишь этом имени).
    fn global_variables(&self) -> Option<HashSet<String>> {
        None
    }

    /// Источник в рабочем состоянии. Сетевой источник может «сломаться» на ходу
    /// (code-index упал, репозиторий пропал) — и тогда он отвечает «имени нет» на
    /// всё. Молча принимать это за истину нельзя: валидатор выдал бы находку
    /// «метод не объявлен» на каждый вызов. Локальные источники всегда исправны.
    fn is_healthy(&self) -> bool {
        true
    }

    /// Счётчики состава: сколько объектов и имён знает источник. `None` —
    /// источник их не считает; тогда в `symbol_sources_status` их не будет.
    fn stats(&self) -> Option<SourceStats> {
        None
    }

    /// Состав источника НЕПРАВДОПОДОБНО мал — индекс пуст или почти пуст
    /// (issue #46).
    ///
    /// Транспорт при этом исправен: `is_healthy` остаётся `true`, и отличить
    /// «нет такого объекта» от «источник ничего не знает» было нечем. По такому
    /// источнику находки о несуществующих объектах и общих модулях понижаются до
    /// `Low`: ответ «не найдено» не доказательство, а следствие пустоты.
    fn is_thin(&self) -> bool {
        false
    }

    /// Человекочитаемое имя источника (для /health и логов).
    fn describe(&self) -> String;
}
