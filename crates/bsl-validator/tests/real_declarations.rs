#[test]
fn real_platform_failures_are_caught() {
    let Some(path) = hbk_path() else {
        eprintln!("skip: hbk не найден (задайте BSL_CONTEXT_PLATFORM_PATH)");
        return;
    };
    let index = load_from_hbk(&path).expect("PlatformIndex");

    let mut caught = 0usize;
    let mut expected = 0usize;
    let mut regressions = Vec::new();

    for (title, src, want) in cases() {
        let result = validate_module_with_profile(&index, src, Some(FORM), None, 3, Profile::Full);
        let got = !result.errors.is_empty();

        if want {
            expected += 1;
        }
        if got {
            caught += 1;
        }

        let mark = if got { "ЛОВИТ  " } else { "ПРОПУСК" };
        println!("{mark} {title}");
        for err in result.errors.iter().take(2) {
            println!(
                "        · {:?} [{:?}] стр.{}: {}",
                err.kind, err.confidence, err.line, err.message
            );
        }

        if want && !got {
            regressions.push(title);
        }
    }

    println!("\nловится {caught} из {}", cases().len());
    assert!(
        regressions.is_empty(),
        "перестали ловиться реальные отказы: {regressions:?}"
    );
    assert_eq!(expected, 9, "состав ожиданий изменился — обновите комментарий");
}
